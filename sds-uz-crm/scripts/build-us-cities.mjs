// Regenerates src/usCities.data.js from the GeoNames US postal-code dump.
//
//   curl -LO https://download.geonames.org/export/zip/US.zip && unzip US.zip
//   node scripts/build-us-cities.mjs path/to/US.txt
//
// Output: one line per city — "City|ST|zipzipzip…" (5-digit ZIPs concatenated),
// covering the 50 states + DC. Cities are ordered by ZIP count (a proxy for
// size) so the biggest match shows first in the From/To search.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const STATES = new Set('AL AK AZ AR CA CO CT DE DC FL GA HI ID IL IN IA KS KY LA ME MD MA MI MN MS MO MT NE NV NH NJ NM NY NC ND OH OK OR PA RI SC SD TN TX UT VT VA WA WV WI WY'.split(' '));

const src = process.argv[2];
if (!src) throw new Error('Usage: node scripts/build-us-cities.mjs path/to/US.txt');

const byCity = new Map();
for (const line of readFileSync(src, 'utf8').split('\n')) {
  const [, zip, city, , state] = line.split('\t');
  if (!STATES.has(state) || !/^\d{5}$/.test(zip || '') || !city) continue;
  // GeoNames writes "Mcallen"; the USPS spelling is "McAllen".
  const name = city.trim().replace(/\|/g, ' ').replace(/\bMc([a-z])/g, (_, c) => `Mc${c.toUpperCase()}`);
  const key = `${name}|${state}`;
  if (!byCity.has(key)) byCity.set(key, []);
  byCity.get(key).push(zip);
}

const rows = [...byCity.entries()]
  .map(([key, zips]) => [key, [...new Set(zips)].sort()])
  .sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]));

const body = rows.map(([key, zips]) => `${key}|${zips.join('')}`).join('\n');
const out = `// GENERATED by scripts/build-us-cities.mjs — do not edit by hand.
// Source: GeoNames postal codes (https://www.geonames.org), CC BY 4.0.
// ${rows.length} cities, ${rows.reduce((n, r) => n + r[1].length, 0)} ZIP codes, 50 states + DC.
export default ${JSON.stringify(body)};
`;
writeFileSync(fileURLToPath(new URL('../src/usCities.data.js', import.meta.url)), out);
console.log(`Wrote ${rows.length} cities.`);
